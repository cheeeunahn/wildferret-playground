// 질문 정의를 API가 받는 모양으로 옮긴다. `legend`와 `display`는 화면이
// 쓰려고 들고 있는 것일 뿐이므로 요청에는 싣지 않는다.
export function buildQuestions() {
  return Object.fromEntries(
    Object.entries(DRAWING_QUESTIONS).map(([key, q]) => [
      key,
      { type: q.primitive, instructions: q.instructions, criteria: q.criteria },
    ]),
  );
}

// 패널에 넘길 질문. 화면용 문구가 있으면 그것으로 갈아 끼운다.
export function questionForDisplay(key) {
  const question = DRAWING_QUESTIONS[key];
  if (!question.display) return question;
  return { ...question, criteria: question.display };
}
